CREATE TABLE IF NOT EXISTS leads (
 id TEXT PRIMARY KEY, request_key TEXT NOT NULL UNIQUE, email TEXT NOT NULL,
 data TEXT NOT NULL, edit_hash TEXT NOT NULL, verified INTEGER NOT NULL DEFAULT 0,
 status TEXT NOT NULL DEFAULT 'NEW', plan TEXT, revision INTEGER NOT NULL DEFAULT 1,
 note TEXT NOT NULL DEFAULT '', error TEXT, hubspot_status TEXT NOT NULL DEFAULT 'pending',
 created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL, lease_until INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS leads_pending ON leads(status,verified,lease_until);
CREATE TABLE IF NOT EXISTS areas (id TEXT PRIMARY KEY, data TEXT NOT NULL, updated_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS cities (id TEXT PRIMARY KEY, data TEXT NOT NULL, updated_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS auth_tokens (hash TEXT PRIMARY KEY, purpose TEXT NOT NULL, subject TEXT NOT NULL, expires_at INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions (hash TEXT PRIMARY KEY, role TEXT NOT NULL, subject TEXT NOT NULL, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS outbox (id TEXT PRIMARY KEY, type TEXT NOT NULL, lead_id TEXT, payload TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'pending', attempts INTEGER NOT NULL DEFAULT 0, available_at INTEGER NOT NULL, provider_id TEXT, error TEXT, updated_at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS outbox_pending ON outbox(state,available_at);
CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS geo_cache (key TEXT PRIMARY KEY, data TEXT NOT NULL, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit (id INTEGER PRIMARY KEY AUTOINCREMENT, lead_id TEXT, action TEXT NOT NULL, created_at INTEGER NOT NULL);
